/**
 * Filter vehicles by make, model, year, and search keywords
 */
export function searchVehicleDatabase(query: {
  make?: string;
  model?: string;
  year?: string;
  keyword?: string;
}): VehicleBatterySpec[] {
  return VEHICLE_BATTERY_DATABASE.filter((spec) => {
    if (query.make && spec.make.toLowerCase() !== query.make.toLowerCase()) {
      return false;
    }
    if (query.model && !spec.model.toLowerCase().includes(query.model.toLowerCase())) {
      return false;
    }
    if (query.keyword) {
      const q = query.keyword.toLowerCase();
      const combined = `${spec.make} ${spec.model} ${spec.years} ${spec.engine} ${spec.groupSize} ${spec.dinCode}`.toLowerCase();
      if (!combined.includes(q)) return false;
    }
    return true;
  });
}

export function getUniqueMakes(): string[] {
  const makes = new Set<string>();
  VEHICLE_BATTERY_DATABASE.forEach((v) => makes.add(v.make));
  return Array.from(makes).sort();
}

export function getModelsByMake(make: string): string[] {
  const models = new Set<string>();
  VEHICLE_BATTERY_DATABASE.filter(
    (v) => v.make.toLowerCase() === make.toLowerCase()
  ).forEach((v) => models.add(v.model));
  return Array.from(models).sort();
}

export function getYearsByMakeAndModel(make: string, model: string): string[] {
  const years = new Set<string>();
  VEHICLE_BATTERY_DATABASE.filter(
    (v) =>
      v.make.toLowerCase() === make.toLowerCase() &&
      v.model.toLowerCase() === model.toLowerCase()
  ).forEach((v) => years.add(v.years));
  return Array.from(years);
}

export function findVehicleBatterySpecs(id: string): VehicleBatterySpec | undefined {
  return VEHICLE_BATTERY_DATABASE.find((v) => v.id === id);
}

